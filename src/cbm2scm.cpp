// ======================================================================
// cbm2scm — ChessBase .cbm (gallery) -> scidb .scm converter
// ======================================================================
// Converts a ChessBase .cbm manifest (parsed by db::cbh::MediaTable) into a
// scidb-native .scm text manifest. v1 emits the gallery level only: every
// distinct media file referenced by the .cbm becomes a [Media Mnnn] entry.
// Per-game linkage is NOT emitted because the .cbm -> game-record linkage
// is not yet reverse-engineered (see CBM_FORMAT_DESIGN.md §5.6). Once the
// linkage is cracked, this tool can be extended to emit [Game HEX] blocks.
//
// Usage: cbm2scm <input.cbm-rootname> <output.scm> [media-dir-name]
//   <input.cbm-rootname> : path without the .cbm suffix (e.g. "Bases/MyBase")
//   <output.scm>          : path to the .scm file to write
//   [media-dir-name]      : name of the media folder (default: "<basename>.media")
// ======================================================================

#include "db/cbh/cbh_media.h"

#include "mstl/m_string.h"
#include "mstl/m_vector.h"

#include "util/u_progress.h"

#include <tcl.h>

#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <string>

namespace tcl { namespace bits { Tcl_Interp* interp = nullptr; } }

struct TclInterpreter
{
	TclInterpreter()  { tcl::bits::interp = Tcl_CreateInterp(); Tcl_Init(tcl::bits::interp); }
	~TclInterpreter() { Tcl_DeleteInterp(tcl::bits::interp); tcl::bits::interp = nullptr; }
};

static mstl::string basename(mstl::string const& path)
{
	// strip directory
	unsigned slash = 0;
	for (unsigned i = 0; i < path.size(); ++i)
		if (path[i] == '/' || path[i] == '\\') slash = i + 1;
	mstl::string base = path.substr(slash);
	// strip trailing .cbm if present
	if (base.size() > 4 &&
		base[base.size()-4] == '.' && base[base.size()-3] == 'c' &&
		base[base.size()-2] == 'b' && base[base.size()-1] == 'm')
	{
		base = base.substr(0, base.size()-4);
	}
	return base;
}

static char const* typeName(db::cbh::MediaTable::MediaType t)
{
	switch (t)
	{
		case db::cbh::MediaTable::Media_Picture: return "picture";
		case db::cbh::MediaTable::Media_Audio:   return "audio";
		case db::cbh::MediaTable::Media_Video:   return "video";
		case db::cbh::MediaTable::Media_Stream:  return "stream";
		default: return "none";
	}
}

static void quoteAndWrite(FILE* fp, mstl::string const& s)
{
	::fputc('"', fp);
	for (unsigned i = 0; i < s.size(); ++i)
	{
		char c = s[i];
		// minimal quoting: escape " and backslash; everything else raw
		if (c == '"' || c == '\\') ::fputc('\\', fp);
		::fputc(c, fp);
	}
	::fputc('"', fp);
}

int main(int argc, char** argv)
{
	if (argc < 3)
	{
		fprintf(stderr, "usage: %s <input-rootname> <output.scm> [media-dir-name]\n", argv[0]);
		fprintf(stderr, "  converts a ChessBase .cbm gallery into a scidb .scm manifest.\n");
		return 2;
	}

	mstl::string inputRoot  = argv[1];
	mstl::string outputPath = argv[2];
	mstl::string mediaDir;
	if (argc >= 4) mediaDir = argv[3];
	else           mediaDir = basename(inputRoot) + ".media";

	TclInterpreter tcl;
	util::Progress& progress = util::Progress::null();

	// Open the .cbm
	db::cbh::MediaTable cbm;
	if (!cbm.read(inputRoot, progress))
	{
		fprintf(stderr, "FAIL: cannot read .cbm at '%s' (missing, unreadable, or parser-rejected)\n",
				(inputRoot + ".cbm").c_str());
		return 1;
	}

	// Collect every distinct media file
	mstl::vector<db::cbh::MediaTable::MediaEntry> entries;
	cbm.collectMediaFiles(entries);

	// De-dup by filename (the same .jpg can be referenced by many bags)
	unsigned distinct = 0;
	for (unsigned i = 0; i < entries.size(); ++i)
	{
		bool seen = false;
		for (unsigned j = 0; j < i; ++j)
			if (entries[j].filename == entries[i].filename) { seen = true; break; }
		if (!seen) ++distinct;
	}

	// Open output
	FILE* fp = std::fopen(outputPath.c_str(), "wb");
	if (!fp)
	{
		fprintf(stderr, "FAIL: cannot open output '%s' for writing\n", outputPath.c_str());
		return 1;
	}

	::fprintf(fp, "# scidb media manifest\n");
	::fprintf(fp, "# generated by cbm2scm (gallery level; per-game linkage not yet converted)\n");
	::fprintf(fp, "[Database ");
	// strip trailing .cbm from advisory database name
	mstl::string db = basename(inputRoot);
	quoteAndWrite(fp, db); ::fprintf(fp, "]\n");
	::fprintf(fp, "[MediaDir ");
	quoteAndWrite(fp, mediaDir); ::fprintf(fp, "]\n");
	::fprintf(fp, "[Encoding \"utf-8\"]\n\n");

	unsigned id = 0;
	for (unsigned i = 0; i < entries.size(); ++i)
	{
		// de-dup
		bool seen = false;
		for (unsigned j = 0; j < i; ++j)
			if (entries[j].filename == entries[i].filename) { seen = true; break; }
		if (seen) continue;

		char idbuf[16];
		std::snprintf(idbuf, sizeof(idbuf), "M%03u", id++);
		::fprintf(fp, "[Media \"%s\"]\n", idbuf);
		::fprintf(fp, "Type: %s\n", typeName(entries[i].type));
		::fprintf(fp, "Path: "); quoteAndWrite(fp, entries[i].filename); ::fprintf(fp, "\n");
		if (!entries[i].type) { /* nothing else */ }
		::fprintf(fp, "\n");
	}

	std::fclose(fp);

	printf("OK: wrote %u distinct media entries (%u total refs) to '%s'\n",
			distinct, unsigned(entries.size()), outputPath.c_str());
	printf("  MediaDir: %s\n", mediaDir.c_str());
	printf("  NOTE: per-game linkage not converted (.cbm bag->game linkage not yet RE'd);\n");
	printf("        the .scm contains the gallery library only. Author [Game HEX] blocks\n");
	printf("        via the scidb authoring UI to attach media to specific games.\n");
	return 0;
}

