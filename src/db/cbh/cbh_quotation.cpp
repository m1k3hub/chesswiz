bool
decodeQuotationMoves(unsigned char const* bytes, unsigned length, mstl::string& san)
{
	if (length < 2 || (length & 1))
		return false;

	Board board(Board::standardBoard(variant::Normal));
	mstl::string text;
	static piece::Type const promotions[] =
		{ piece::Queen, piece::Rook, piece::Bishop, piece::Knight };

	for (unsigned ply = 0; ply < length/2; ++ply)
	{
		unsigned word = unsigned(QuotationLookup[static_cast<unsigned char>(bytes[2*ply] - ply)]) << 8;
		word |= QuotationLookup[static_cast<unsigned char>(bytes[2*ply + 1] - ply)];

		if (word == 0x4000)
		{
			if (2*ply + 2 != length) return false;
			san.swap(text);
			return true;
		}
		// Other control words (e.g. nonstandard starts/variations) are not
		// established by the fixture. Do not reinterpret them as moves.
		if (word & 0xc000) return false;

		Square from = square(word & 63);
		Square to = square((word >> 6) & 63);
		unsigned promotion = (word >> 12) & 3;

		// Match generated legal moves BEFORE calling board mutation or SAN
		// routines; makeMove(from,to) assumes valid input and can assert.
		MoveList legal;
		board.generateMoves(variant::Normal, legal);
		board.filterLegalMoves(legal, variant::Normal);
		Move move;
		for (unsigned i = 0; i < legal.size(); ++i)
		{
			Move const& candidate = legal[i];
			Square target = candidate.isCastling() ? candidate.castlingKingTo() : candidate.to();
			if (candidate.from() != from || target != to) continue;
			if (candidate.isPromotion())
			{
				if (candidate.promoted() != promotions[promotion]) continue;
			}
			else if (promotion != 0)
			{
				continue;
			}
			move = candidate;
			break;
		}
		if (!move) return false;

		board.prepareForPrint(move, variant::Normal, Board::InternalRepresentation);
		if (!text.empty()) text += ' ';
		if ((ply & 1) == 0)
		{
			char number[16];
			::snprintf(number, sizeof(number), "%u.", ply/2 + 1);
			text += number;
		}
		// This API's Scidb protocol includes SAN check/mate suffixes;
		// Standard deliberately omits them.
		move.printSAN(text, protocol::Scidb, encoding::Latin1);
		board.doMove(move, variant::Normal);
	}
	return false; // missing end marker: do not publish a partial replay
}

