PHOTO = re.compile(r'\[image\s+create\s+photo[^\]\n]*?-data\s+\{([^{}]*)\}')
# Explicit mapping table below: file|qualified variable|occurrence -> (SVG, colour).
# Occurrence disambiguates historical duplicate assignments and commented assets.


def embedded(path):
    text = path.read_bytes().decode('latin1')
    matches = list(PHOTO.finditer(text))
    # Track namespace scopes without letting image payloads affect brace nesting.
    masked = list(text)
    for m in matches:
        masked[m.start(1):m.end(1)] = ['\n' if c == '\n' else ' ' for c in m[1]]
    masked = ''.join(masked)
    openings = {m.end()-1: m[1] for m in re.finditer(r'namespace\s+eval\s+([^\s{}]+)\s*\{', masked)}
    scopes, depth, positions = [], 0, {}
    starts = {m.start() for m in matches}
    escaped = False
    for pos, c in enumerate(masked):
        if pos in starts:
            positions[pos] = '::' + '::'.join(n.strip(':') for _, n in scopes)
        if escaped:
            escaped = False
            continue
        if c == '\\':
            escaped = True
        elif c == '{':
            depth += 1
            if pos in openings:
                scopes.append((depth, openings[pos]))
        elif c == '}':
            if scopes and scopes[-1][0] == depth:
                scopes.pop()
            depth -= 1
    counts = {}
    for m in matches:
        prefix = text[text.rfind('\n', 0, m.start())+1:m.start()]
        commented = prefix.lstrip().startswith('#')
        comment_keep = commented and not prefix.lstrip()[1:2].isspace()
        prefix = prefix.lstrip().lstrip('#').strip()
        var = re.sub(r'^(?:set|variable)\s+', '', prefix).strip() or '(anonymous)'
        payload = re.sub(r'(?m)^\s*#\s?', '', m[1]) if commented else m[1]
        payload = re.sub(r'[\s\\]', '', payload)
        if not payload:
            continue  # documented user override, not an embedded image
        raw = base64.b64decode(payload, validate=True)
        im = Image.open(io.BytesIO(raw)).convert('RGBA')
        ns = positions[m.start()]
        qualified = var if var.startswith('::') else ns.rstrip(':') + '::' + var
        if str(path.relative_to(ROOT)).startswith('tcl/themes/ttk/'):
            qualified = ns.rstrip(':') + '::I(' + var + ')'
        counts[qualified] = counts.get(qualified, 0) + 1
        key = f'{path.relative_to(ROOT)}|{qualified}|{counts[qualified]}'
        yield dict(key=key, file=str(path.relative_to(ROOT)), variable=qualified,
                   local=var, line=text.count('\n',0,m.start())+1,
                   size=list(im.size), commented=commented, comment_keep=comment_keep,
                   sha256=hashlib.sha256(raw).hexdigest(), image=im, match=m)


def inventory():
    return [r for p in sorted((ROOT/'tcl').rglob('*.tcl')) for r in embedded(p)]


def sheets(rows, label):
    # Paginated at native size (large non-icon artwork capped at 80px).
    for page in range(math.ceil(len(rows)/120)):
        chunk = rows[page*120:(page+1)*120]
        canvas = Image.new('RGB',(1200,math.ceil(len(chunk)/8)*112),'#f6f6f6')
        d = ImageDraw.Draw(canvas)
        for j,r in enumerate(chunk):
            x,y=(j%8)*150,(j//8)*112
            im=r['image'].copy(); im.thumbnail((90,80))
            # Both a light and dark backdrop make white/black status visible.
            d.rectangle((x+4,y+4,x+70,y+82),fill='#ffffff')
            d.rectangle((x+70,y+4,x+146,y+82),fill='#808080')
            canvas.paste(im,(x+(150-im.width)//2,y+4),im)
            name=r['local']
            d.text((x+4,y+84),f'{page*120+j+1:04d} {name[:21]}',fill='black')
            d.text((x+4,y+98),f'{r["size"][0]}x{r["size"][1]}',fill='black')
        canvas.save(OUT/f'{label}-{page+1:02d}.png')


def write_inventory(rows):
    # Literal reference search includes Tcl's dynamic array lookups; report them
    # as lexical use sites, not a claim of complete runtime call resolution.
    sources = {str(p.relative_to(ROOT)): p.read_bytes().decode('latin1').splitlines()
               for p in (ROOT/'tcl').rglob('*.tcl')}
    uses={}
    for file,lines in sources.items():
        for n,line in enumerate(lines,1):
            if 'image create photo' in line or line.lstrip().startswith('#'):
                continue
            # Tcl identifiers and array base names; conservative lexical uses.
            for token in set(re.findall(r'[A-Za-z_][A-Za-z_0-9-]*',line)):
                uses.setdefault(token,[]).append(f'{file}:{n}: {line.strip()}')
    serial=[]
    for r in rows:
        base=r['local'].split('(')[0].split('::')[-1]
        q={k:v for k,v in r.items() if k not in ('image','match')}
        q['where_used']=uses.get(base,[])
        serial.append(q)
    (OUT/'inventory.json').write_text(json.dumps(serial,indent=2)+'\n')
    lines=['# Embedded image inventory','',
           'All literal braced `image create photo -data` images, including commented payloads.',
           'Use sites are lexical references (including dynamic array lookups); commented images are inactive.', '',
           '| # | File:line | Variable | Pixels | Active | Use sites |','|---|---|---|---|---|---|']
    for i,r in enumerate(serial,1):
        sites=', '.join(x.split(': ',1)[0] for x in r['where_used']) or 'no literal reference; see surrounding namespace/array consumer'
        lines.append(f'| {i} | {r["file"]}:{r["line"]} | `{r["variable"]}` | {r["size"][0]}×{r["size"][1]} | {not r["commented"]} | {sites} |')
    (OUT/'inventory.md').write_text('\n'.join(lines)+'\n')


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--inventory-only',action='store_true')
    parser.add_argument('--archive',type=Path)
    args=parser.parse_args(); OUT.mkdir(parents=True,exist_ok=True)
    rows=inventory()
    if args.inventory_only:
        write_inventory(rows); sheets(rows,'before')
        print(f'Inventoried {len(rows)} embedded images.'); return
    if not MAPPING:
        raise RuntimeError('Mapping table is empty')
    keys={r['key'] for r in rows}
    retained={r['key'] for r in rows if r['file'] in ('tcl/utils/countries.tcl','tcl/splash.tcl')
              or (r['file']=='tcl/icons.tcl' and r['local']=='logo')}
    if keys != set(MAPPING) | retained:
        raise RuntimeError(f'Unmapped embedded images: {keys - set(MAPPING) - retained}')
    if set(MAPPING)-keys:
        raise RuntimeError(f'Mapping keys missing from source: {set(MAPPING)-keys}')
    archive=args.archive or OUT/f'tabler-icons-v{VERSION}.tar.gz'
    if not archive.exists():
        with urllib.request.urlopen(URL,timeout=120) as response:
            archive.write_bytes(response.read())
    if hashlib.sha256(archive.read_bytes()).hexdigest()!=SHA256:
        raise RuntimeError('Tabler archive SHA256 mismatch')
    wanted={f'tabler-icons-{VERSION}/icons/outline/{name}.svg':name
            for name,colour in MAPPING.values() if not name.startswith('original:')}
    svg_sources={}
    with tarfile.open(archive,mode='r|gz') as tar:
        for member in tar:
            if member.name == f'tabler-icons-{VERSION}/LICENSE':
                license_text=tar.extractfile(member).read().decode()
            elif member.name in wanted:
                svg_sources[wanted[member.name]]=tar.extractfile(member).read().decode()
    if set(wanted.values()) != set(svg_sources):
        raise RuntimeError('Mapped SVG missing from pinned archive')
    # Also embedded into each PNG so current Tcl-only installation carries notice.
    notice=f'Tabler Icons v{VERSION}: {URL}\nSHA256: {SHA256}\n\n'+license_text
    (ROOT/'tcl/icons-LICENSE').write_text(notice+'\nOriginal SVG exceptions and all cursor drawings: Chesswiz contributors, 2026, GPL-2.0-or-later. See COPYING.\n')
    edits={}; rendered={}
    from PIL.PngImagePlugin import PngInfo
    for r in rows:
        if r['key'] not in MAPPING: continue
        name,colour=MAPPING[r['key']]
        if name.startswith('original:'):
            svg=original_svg(name[9:],colour,r)
            src=ROOT/'tcl/cursor/icon-sources'/f'{name[9:]}.svg'
            src.parent.mkdir(parents=True,exist_ok=True); src.write_text(svg)
            lic='Original Chesswiz artwork, 2026. GPL-2.0-or-later; see COPYING.'
        else:
            svg=svg_sources[name].replace('currentColor',colour)
            if colour in ('#ffffff','#f8fafc'):
                # White side markers need a dark halo on light UI backgrounds.
                import xml.etree.ElementTree as ET
                import copy
                element=ET.fromstring(svg)
                under=copy.deepcopy(element)
                under.set('stroke','#334155'); under.set('stroke-width','4')
                element.insert(0,under)
                svg=ET.tostring(element,encoding='unicode')
            lic=notice
        cache=(svg,tuple(r['size']))
        if cache not in rendered:
            raw=cairosvg.svg2png(bytestring=svg.encode(),output_width=r['size'][0]*4,output_height=r['size'][1]*4)
            im=Image.open(io.BytesIO(raw)).convert('RGBA').resize(tuple(r['size']),Image.Resampling.LANCZOS)
            info=PngInfo(); info.add_text('License',lic)
            buf=io.BytesIO(); im.save(buf,format='PNG',pnginfo=info)
            rendered[cache]=(im,base64.b64encode(buf.getvalue()).decode())
        im,b64=rendered[cache]
        prefix=('#' if r['comment_keep'] else '# ') if r['commented'] else '\t'
        replacement='\n'+'\n'.join(prefix+s for s in textwrap.wrap(b64,76))+'\n'+(prefix if r['commented'] else '')
        edits.setdefault(r['file'],[]).append((r['match'].start(1),r['match'].end(1),replacement))
        r['image']=im
    for file,changes in edits.items():
        path=ROOT/file; text=path.read_bytes().decode('latin1')
        for start,end,data in sorted(changes,reverse=True): text=text[:start]+data+text[end:]
        path.write_bytes(text.encode('latin1'))
    sheets(rows,'after')
    (OUT/'mapping.json').write_text(json.dumps(MAPPING,indent=2)+'\n')
    print(f'Replaced {len(MAPPING)} images in {len(edits)} Tcl files.')

# ORIGINAL_SVG and MAPPING definitions follow.

def original_svg(name,colour,row):
    """Original geometric controls: no font or third-party artwork involved."""
    w,h=row['size']; body=''; view='0 0 24 24'
    if name.startswith('squares-'):
        code=name[8:]; cells=list(code) if len(code)==4 else [code[0],code[1],code[1],code[0]]
        body=''.join(f'<rect x="{(i%2)*12}" y="{(i//2)*12}" width="12" height="12" fill="{dict(l="#f1e5cf",d="#7d6550")[c]}"/>' for i,c in enumerate(cells))
    elif name.startswith('stm-'):
        fill,stroke=('#ffffff','#334155') if name.endswith('white') else ('#111827','#e2e8f0')
        body=f'<circle cx="12" cy="12" r="10" fill="{fill}" stroke="{stroke}" stroke-width="2"/>'
    elif name.startswith('board-'):
        shape=name[6:]
        body={'circle':f'<circle cx="12" cy="12" r="10" fill="none" stroke="{colour}" stroke-width="2"/>','disk':f'<circle cx="12" cy="12" r="11" fill="{colour}"/>','square':f'<rect x="1" y="1" width="22" height="22" fill="none" stroke="{colour}" stroke-width="2"/>'}[shape]
    elif name.startswith('theme-'):
        control=re.sub(r'^theme-(clearlooks|scidblue)-','',name).rsplit('-',1)[0]
        kind,state=(control.rsplit('-',1)+[''])[:2] if '-' in control else (control,'')
        # Explicit state palette: disabled, normal, active/hover, pressed, selected.
        fill={'d':'#eeeeee','n':'#e8e8e8','a':'#dbeafe','p':'#bfdbfe','pa':'#bfdbfe','s':'#bfdbfe','default':'#dbeafe'}.get(state,'#e8e8e8')
        ink='#a3a3a3' if state.startswith('d') else '#334155'
        arrow={'arrowleft':'M15 5L8 12L15 19','arrowright':'M9 5L16 12L9 19','arrowup':'M5 15L12 8L19 15','arrowdown':'M5 9L12 16L19 9','comboarrow':'M5 9L12 16L19 9','spinarrowdown':'M5 9L12 16L19 9','spinarrowup':'M5 15L12 8L19 15'}
        if kind in arrow:body=f'<path d="{arrow[kind]}" fill="none" stroke="{ink}" stroke-width="2.5" stroke-linecap="round" stroke-linejoin="round"/>'
        elif kind in ('check','radio'):
            body=f'<rect x="3" y="3" width="18" height="18" rx="2" fill="#fafafa" stroke="{ink}" stroke-width="2"/>' if kind=='check' else f'<circle cx="12" cy="12" r="9" fill="#fafafa" stroke="{ink}" stroke-width="2"/>'
            if state.endswith('c'):
                body+=f'<path d="M6 12L10 16L18 7" fill="none" stroke="{ink}" stroke-width="2.5"/>' if kind=='check' else f'<circle cx="12" cy="12" r="5" fill="{ink}"/>'
        elif kind=='sizegrip':body=f'<path d="M5 21L21 5M12 21L21 12M19 21L21 19" stroke="{ink}" stroke-width="1.5"/>'
        elif kind=='blank':body=''
        elif kind in ('sep','scaletrough'):
            view=f'0 0 {w} {h}';body=f'<rect width="{w}" height="{h}" fill="#b0b0b0"/>'
        else:
            # Pixel-space border keeps the original nine-slice element borders.
            view=f'0 0 {w} {h}'
            fill= '#3b82f6' if kind=='progress' else fill
            if kind=='tree':fill='#fafafa'
            body=f'<rect x="0.5" y="0.5" width="{max(0,w-1)}" height="{max(0,h-1)}" rx="{min(2,w/4,h/4)}" fill="{fill}" stroke="{colour}" stroke-width="1"/>'
    else: raise ValueError(name)
    return f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" viewBox="{view}"><!-- Original Chesswiz artwork, 2026; GPL-2.0-or-later. -->{body}</svg>\n'

